import { readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { generatePage } from "./genpage.ts";
import { ownership, signGenerated } from "./ownership.ts";
import type { DesignFingerprintV1 } from "./types.ts";

// Code only. For the full flow (assets + routing + verification) use `npm run build-page`.
function usage(): never { console.error("Usage: npm run genpage -- --design outputs/my-design --out path/To/Page.tsx [--component Name] [--emit react|html] [--lib ../lib] [--asset-base /assets]"); process.exit(1); }
const args = process.argv.slice(2);
const value = (flag: string): string | undefined => { const index = args.indexOf(flag); return index >= 0 ? args[index + 1] : undefined; };
const designDir = value("--design"); const outPath = value("--out");
if (!designDir || !outPath) usage();
const emit = value("--emit") ?? (outPath.endsWith(".html") ? "html" : "react"); if (!["react", "html"].includes(emit)) usage();

const fingerprint = JSON.parse(await readFile(join(designDir, "fingerprint.json"), "utf8")) as DesignFingerprintV1;
const fallbackName = basename(outPath).replace(/\.(tsx?|html)$/, "").replace(/[^A-Za-z0-9]/g, "") || "GeneratedPage";
const result = generatePage(fingerprint, { component: value("--component") ?? fallbackName, emit: emit as "react" | "html", libPath: value("--lib"), assetBase: value("--asset-base"), source: designDir });
// Same guard as build-page: only this tool's own, unedited output may be replaced.
const existing = await readFile(outPath, "utf8").catch(() => undefined);
if (existing !== undefined && ownership(existing) !== "generated") { console.error(`Refusing to overwrite ${outPath}: it ${ownership(existing) === "edited" ? "was generated by figma2code and edited afterwards" : "was not generated by figma2code"}. Choose another --out.`); process.exit(1); }
await writeFile(outPath, signGenerated(result.code));
console.log(JSON.stringify({ status: "ok", out: outPath, lines: result.code.split("\n").length, elements: result.ir.stats.emitted, flats: result.flats.map((flat) => `${flat.file} (${flat.reason})`), images: result.images.length, fonts: result.fonts, notes: result.notes.slice(0, 10) }, null, 2));
